// 소스코드 작성
#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>

int main(void)
{
    char str[20];
    char ch;
    int i = 0;

    printf("문자열을 입력하시오 : ");

    
    while (1) 
    {
        scanf("%c", &ch); 

        if (ch == '\n') 
        { 
            break;
        }

        str[i] = ch; 
        i++;
    }

    printf("문자열: %s\n", str);

    return 0;
}

// **********************************************
// 제 목 : 문자를 입력하여 문자출력하는 프로그램
// 날 짜 : 2026년 10월14일
// 작성자 : 2600038 김부성
// **********************************************
// 소스코드 작성
#define _CRT_SECURE_NO_WARNINGS 
#include <stdio.h>

int main(void)
{
    char ch;
    int i;

    for (i = 0; i < 5; i++)
    {
        printf("문자 입력:");

        /* -------------------------------------------------------------
         * 방법 1: 공백 지정자 사용 (" %c")
         * %c 앞에 한 칸의 공백을 두면 버퍼에 남은 엔터('\n')를 자동 무시합니다.
         * ------------------------------------------------------------- */
        scanf(" %c", &ch); 


        /* -------------------------------------------------------------
         * 방법 2: getchar() 함수 사용
         * 기존 scanf("%c", &ch);를 그대로 쓸 때는 아래 주석을 풀어서 
         * 버퍼에 남은 엔터('\n')를 직접 읽어내어 지워줘야 합니다.
         * -------------------------------------------------------------
         * scanf("%c", &ch);
         * getchar(); // 버퍼의 엔터키(\n)를 제거하는 역할
         * ------------------------------------------------------------- */

        printf("문자: %c\n", ch);
    }

    return 0;
}


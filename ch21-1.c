#define _CRT_SECURE_NO_WARNINGS 
#include <stdio.h>
int main(void) 
{
    char ch;

    while (1) 
    {
        printf("문자입력 : ");
        scanf(" %c", &ch);

        if (ch == 'q' || ch == 'Q') 
        {
            break; 
        }

        printf("입력된 문자는 %c\n", ch);
    }

    return 0;
}


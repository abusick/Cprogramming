// 날 짜 : 2026년 9월11일
// 작성자 : 2600038
// **********************************************
// 소스코드 작성
/**
 * @file main5.c
 * @brief 실습과제 5: 포인터 덧셈 연산을 이용한 실수 배열 제어 및 5가지 표현식 검증
 * @details 키보드로부터 5개의 실수를 입력받고, 5가지 서로 다른 배열/포인터 표현 방식으로 
 *          데이터를 제어하며 동일한 메커니즘을 증명합니다.
 */

#include <stdio.h>

int main(void)
{
    double arr[5];
    double *ptr = arr;
    int i;

    printf("=== 실습과제 5: 5가지 방식의 배열 및 포인터 표현 검증 ===\n\n");

    for(i = 0; i < 5; i++)
    {
        printf("%d번째 실수를 입력하시오: ", i + 1);
        scanf("%lf", (ptr + i)); 
    }
    printf("\n");



    // -----------------------------------------------------------------
    // 방식 1: 배열 이름 + 인덱스 표현식 (기본 배열 문법)
    // -----------------------------------------------------------------
    printf("방식 1 [arr[i]]: ");
    for(i = 0; i < 5; i++) {
        printf("%.2f ", arr[i]);
    }
    printf("\n");

    // -----------------------------------------------------------------
    // 방식 2: 배열 이름을 포인터처럼 사용한 덧셈 연산식
    // -----------------------------------------------------------------
    printf("방식 2 [*(arr + i)]: ");
    for(i = 0; i < 5; i++) {
        printf("%.2f ", *(arr + i));
    }
    printf("\n");

    // -----------------------------------------------------------------
    // 방식 3: 포인터 변수 + 인덱스 표현식 (포인터를 배열 이름처럼 사용)
    // -----------------------------------------------------------------
    printf("방식 3 [ptr[i]]: ");
    for(i = 0; i < 5; i++) {
        printf("%.2f ", ptr[i]);
    }
    printf("\n");

    // -----------------------------------------------------------------
    // 방식 4: 포인터 변수 + 덧셈 연산식 (본 문제에서 요구한 핵심 방식)
    // -----------------------------------------------------------------
    printf("방식 4 [*(ptr + i)]     : ");
    for(i = 0; i < 5; i++) {
        *(ptr + i) += 2.0; 
        printf("%.2f ", *(ptr + i));
    }
    printf(" (값 +2.0 가산 반영됨)\n");

    // -----------------------------------------------------------------
    // 방식 5: 포인터 변수 자체를 증감시키는 방식 (참고 및 대조용)
    // -----------------------------------------------------------------
    printf("방식 5 [*ptr++ 후 리셋] : ");
    for(i = 0; i < 5; i++) {
        printf("%.2f ", *ptr);
        ptr++; 
    }
    printf("\n");

    return 0;
}
